// Links against the vendored WinDivert import library and places WinDivert.dll and the signed
// WinDivert64.sys next to the built executable (WinDivert loads the driver from the DLL's folder).
use std::path::PathBuf;
use std::{env, fs};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let vendor = manifest.join("vendor").join("windivert");
    println!("cargo:rustc-link-search=native={}", vendor.display());
    println!("cargo:rerun-if-changed=vendor/windivert");
    println!("cargo:rerun-if-changed=resources/resources.json");
    let resources = manifest.join("resources").join("resources.json");

    // OUT_DIR is target/<profile>/build/<pkg>-<hash>/out
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    if let Some(profile_dir) = out.ancestors().nth(3) {
        for dir in [profile_dir.to_path_buf(), profile_dir.join("deps")] {
            let _ = fs::create_dir_all(&dir);
            for f in ["WinDivert.dll", "WinDivert64.sys"] {
                if let Err(e) = fs::copy(vendor.join(f), dir.join(f)) {
                    println!("cargo:warning=could not copy {f} to {}: {e}", dir.display());
                }
            }
            // Scriptlet and $redirect resources (generated by scripts/build-resources.mjs).
            if resources.exists() {
                let _ = fs::copy(&resources, dir.join("resources.json"));
            }
        }
    }

    // AdHush icon and version info (installer/adhush.rc).
    println!("cargo:rerun-if-changed=../installer/adhush.rc");
    println!("cargo:rerun-if-changed=../installer/adhush.ico");
    embed_resource::compile("../installer/adhush.rc", embed_resource::NONE).manifest_optional().unwrap();
}
