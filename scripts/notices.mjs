function crateRows() {
  const seen = new Map();
  for (const c of CRATES) {
    const out = execFileSync('cargo', ['tree', '-e', 'normal', '--target', 'x86_64-pc-windows-msvc', '--prefix', 'none', '--format', '{p}|{l}|{r}'], {
      cwd: path.join(ROOT, c), encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],
    });
    for (const line of out.split(/\r?\n/)) {
      const [pkg, license, repo] = line.split('|');
      if (!pkg || pkg.startsWith('adhush-') || pkg.includes(' (*)')) continue;
      const [name, version] = pkg.trim().split(' ');
      seen.set(`${name} ${version}`, { name, version: version.replace(/^v/, ''), license: license || 'see source', repo: (repo || '').trim() });
    }
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

const rows = crateRows();
const body = `${HEADER}
${rows.length} crates.

| Crate | Version | Licence | Source |
|---|---|---|---|
${rows.map((r) => `| ${r.name} | ${r.version} | ${r.license.replace(/\|/g, '/')} | ${r.repo} |`).join('\n')}
`;
fs.writeFileSync(path.join(ROOT, 'THIRD-PARTY-NOTICES.md'), body);
const licences = {};
for (const r of rows) licences[r.license] = (licences[r.license] || 0) + 1;
